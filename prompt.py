def build_screenshot_user_prompt(app=None, window_title=None):
    """Build the user message for screenshot analysis.

    若提供前台应用上下文，会引导 AI 聚焦该应用窗口，提升精确度。
    """
    if app:
        ctx_lines = [f"【当前活跃应用】{app}"]
        if window_title:
            # 窗口标题帮 AI 判断在操作哪个文件/网页/对话，但要提示不要复述标题原文
            ctx_lines.append(f"【当前窗口标题】{window_title}")
        ctx = "\n".join(ctx_lines)
        return (
            f"{ctx}\n\n"
            "请重点分析上述活跃应用窗口中的工作内容，其他窗口仅作辅助参考。\n"
            "窗口标题可帮你判断具体在操作哪个文件/网页/对话场景，"
            "但不要逐字复述标题内容，也不要泄露其中的账号/路径等敏感信息。\n"
            "用中文描述当前正在进行的工作活动。"
        )
    return "请分析这张屏幕截图，用中文描述当前正在进行的工作活动。"


